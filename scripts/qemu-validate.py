#!/usr/bin/env python3
"""Boot the isp-image in QEMU, exercise the ISP channel, and collect evidence.

    scripts/qemu-validate.py [--image-dir DIR] [--out DIR] [--soak SECONDS]

Drives the guest over its serial console (pexpect), so it needs nothing in the
image beyond a root login. It

  1. boots a scratch copy of the root filesystem with run-qemu.sh,
  2. waits for the isp-channel service started by systemd,
  3. lets it run for --soak seconds while sampling CPU and memory,
  4. changes controls and triggers snapshots (socket and signal),
  5. stops the service cleanly and runs the ISP thread-scaling benchmark,
  6. saves the boot log and the journal, powers the guest off,
  7. pulls the recordings and snapshots out of the ext4 image with debugfs,
  8. writes measurements.md and fails if any acceptance check fails.

Host requirements: qemu-system-aarch64, python3-pexpect, e2fsprogs (debugfs);
ffprobe is used when available.
"""
import argparse
import glob
import os
import re
import shutil
import subprocess
import sys
import tempfile
import time

import pexpect

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ROOTFS = "isp-image-qemuarm64.rootfs.ext4"
DONE = re.compile(r"__DONE_(\d+)__")
RING_FILES = 10  # max-files of the splitmuxsink in the shipped pipeline


class Guest:
    """Serial-console session with a command/exit-status protocol."""

    def __init__(self, image_dir, boot_log):
        self.log = open(boot_log, "w", encoding="utf-8", errors="replace")
        self.child = pexpect.spawn(os.path.join(ROOT, "run-qemu.sh"), [image_dir],
                                   encoding="utf-8", codec_errors="replace", timeout=120)
        self.child.logfile_read = self.log

    def login(self, timeout):
        self.child.expect(r"login: ", timeout=timeout)
        self.child.sendline("root")
        self.child.expect(r"[#$] ", timeout=60)
        # No echo and no line wrapping: command output comes back verbatim.
        self.child.sendline("stty -echo cols 250; export PAGER=cat SYSTEMD_PAGER=cat")
        self.child.expect(r"[#$] ", timeout=30)

    def run(self, command, timeout=120, check=True):
        self.child.sendline(f"{command}; echo __DONE_$?__")
        self.child.expect(DONE, timeout=timeout)
        status = int(self.child.match.group(1))
        output = self.child.before.replace("\r", "").strip()
        self.child.expect(r"[#$] ", timeout=30)
        if check and status != 0:
            raise RuntimeError(f"guest command failed ({status}): {command}\n{output}")
        return output

    def poweroff(self):
        self.child.sendline("poweroff")
        self.child.expect(pexpect.EOF, timeout=300)
        self.child.close()
        self.log.close()


def parse_stats(journal):
    """Returns the list of 'stats' intervals and the final 'summary' as dicts."""
    def fields(line):
        return {k: v for k, v in (kv.split("=", 1) for kv in line.split() if "=" in kv)}

    stats, summary = [], None
    for line in journal.splitlines():
        if "isp-channel: stats " in line:
            stats.append(fields(line.split("isp-channel: stats ", 1)[1]))
        elif "isp-channel: summary " in line:
            summary = fields(line.split("isp-channel: summary ", 1)[1])
    return stats, summary


def column(stats, key):
    return [float(s[key]) for s in stats if key in s]


def write_measurements(path, args, stats, summary, samples, bench, psnr, encoded):
    # The first interval contains start-up (plugin scan, first-touch faults).
    steady = stats[1:] if len(stats) > 2 else stats
    fps = column(steady, "fps")

    def mean(key):
        values = column(steady, key)
        return sum(values) / len(values) if values else float("nan")

    rss = column(stats, "rss_mib")
    lines = [
        "# QEMU measurements",
        "",
        "Generated by `scripts/qemu-validate.py`. **QEMU timings do not represent a real",
        "board:** the guest CPU is emulated instruction by instruction (TCG, no KVM), so",
        "absolute frame times are tens of times worse than on a Cortex-A72 and depend on",
        "the host. The numbers show stability, relative cost per stage and thread scaling.",
        "",
        f"- Guest: qemuarm64, `-cpu cortex-a57 -smp {args.smp} -m {args.mem}`",
        f"- Soak duration: {float(summary['seconds']):.0f} s of streaming, "
        f"{summary['frames']} frames",
        "",
        "| Metric | Value |",
        "| --- | --- |",
        "| Viewfinder stream (libcamera, NV12 1920x1080) | "
        f"{float(summary['avg_fps']):.2f} fps average |",
        "| RAW stream (mosaic step, RGGB 10-bit 1920x1080) | same frames, 1:1 |",
        "| Encoded stream (H.264 in MP4) | "
        + (f"{encoded} frames" if encoded is not None else "not counted (no ffprobe)") + " |",
        f"| FPS per {args.stats_interval} s interval, steady state | "
        f"min {min(fps):.2f} / mean {sum(fps) / len(fps):.2f} / max {max(fps):.2f} |",
        f"| Dropped frames | {summary['dropped']} |",
        f"| Failed or cancelled frames | {summary['failed']} |",
        f"| Per-frame time, virtual sensor (mosaic) | {mean('sensor_ms'):.1f} ms |",
        f"| Per-frame time, software ISP | {mean('isp_ms'):.1f} ms |",
        f"| Per-frame time, encoder hand-off (back-pressure) | {mean('encode_ms'):.1f} ms |",
        f"| Per-frame time, total | {mean('frame_ms'):.1f} ms "
        f"(worst {float(summary['worst_frame_ms']):.1f} ms) |",
        f"| CPU, isp-channel process (400 % = 4 cores) | {mean('cpu_pct'):.0f} % |",
        f"| Memory (RSS), first / last interval | {rss[0]:.1f} / {rss[-1]:.1f} MiB |",
        f"| Memory (RSS), min / max after warm-up | {min(rss[1:] or rss):.1f} / "
        f"{max(rss[1:] or rss):.1f} MiB |",
        f"| ISP round trip vs source picture (snapshot self-test) | {psnr} dB PSNR |",
        "",
        "## Memory over time",
        "",
        "| Streaming time | Frames | FPS | RSS (MiB) | CPU % |",
        "| --- | --- | --- | --- | --- |",
    ]
    step = max(1, len(stats) // 12)
    for i in range(0, len(stats), step):
        s = stats[i]
        lines.append(f"| {(i + 1) * args.stats_interval} s | {s['frames']} | {s['fps']} | "
                     f"{s['rss_mib']} | {s['cpu_pct']} |")
    lines += ["", "## System view during the soak (`top` in the guest)", "", "```"]
    lines += samples
    lines += ["```", "", "## ISP thread scaling in the guest (`isp-bench`, service stopped)",
              "", "```", bench, "```", ""]
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--image-dir", default=os.path.join(ROOT, "build/tmp/deploy/images/qemuarm64"))
    parser.add_argument("--out", default=os.path.join(ROOT, "docs/evidence/qemu"))
    parser.add_argument("--soak", type=int, default=600, help="seconds of streaming to observe")
    parser.add_argument("--smp", type=int, default=4)
    parser.add_argument("--mem", type=int, default=1024)
    parser.add_argument("--stats-interval", type=int, default=10,
                        help="stats-interval of the image's isp-channel.conf")
    parser.add_argument("--boot-timeout", type=int, default=900)
    args = parser.parse_args()

    os.makedirs(args.out, exist_ok=True)
    os.environ["QEMU_SMP"], os.environ["QEMU_MEM"] = str(args.smp), str(args.mem)

    work = tempfile.mkdtemp(prefix="isp-qemu-")
    os.symlink(os.path.realpath(os.path.join(args.image_dir, "Image")), os.path.join(work, "Image"))
    rootfs = os.path.join(work, ROOTFS)
    subprocess.check_call(["cp", "--sparse=always", os.path.realpath(os.path.join(args.image_dir, ROOTFS)), rootfs])

    failures = []

    def check(condition, message):
        print(("PASS " if condition else "FAIL ") + message, flush=True)
        if not condition:
            failures.append(message)

    guest = Guest(work, os.path.join(args.out, "boot.log"))
    try:
        t0 = time.time()
        guest.login(args.boot_timeout)
        print(f"guest reached login in {time.time() - t0:.0f} s", flush=True)

        info = [guest.run(c, check=False) for c in (
            "uname -a", "grep PRETTY_NAME /etc/os-release", "nproc", "free -m",
            "ls -l /dev/dma_heap/ /dev/udmabuf", "id ispchannel", "systemd-analyze")]

        # The unit is enabled; wait for systemd to have it running.
        for _ in range(60):
            if guest.run("systemctl is-active isp-channel", check=False) == "active":
                break
            time.sleep(5)
        check(guest.run("systemctl is-active isp-channel", check=False) == "active",
              "isp-channel.service is active after boot")
        info.append(guest.run("systemctl status isp-channel --no-pager -l | head -15", check=False))

        # Soak: let it stream, sampling the system once a minute.
        samples = []
        end = time.time() + args.soak
        while time.time() < end:
            time.sleep(min(60, max(1, end - time.time())))
            samples.append(guest.run("top -b -n 1 | head -8", check=False))
            samples.append("")
            print(guest.run("isp-ctl get | tail -1", check=False), flush=True)

        # Controls and snapshot triggers.
        guest.run("isp-ctl snapshot")                       # reference picture
        time.sleep(args.stats_interval)
        guest.run("isp-ctl set Brightness 0.15")
        guest.run("isp-ctl set AwbMode tungsten")
        time.sleep(args.stats_interval)
        guest.run("systemctl kill -s USR1 isp-channel")     # snapshot by signal
        time.sleep(args.stats_interval)
        guest.run("isp-ctl set AwbMode auto")
        guest.run("isp-ctl set Brightness 0")
        check(guest.run("isp-ctl set Contrast 9", check=False).startswith("ERROR"),
              "out-of-range control value is rejected")
        time.sleep(2 * args.stats_interval)

        # Clean stop: SIGTERM must finalise the MP4 and print the summary.
        guest.run("systemctl stop isp-channel", timeout=180)
        bench = guest.run("isp-bench 1920 1080 3", timeout=900, check=False)

        journal = guest.run("journalctl -u isp-channel --no-pager -o short-monotonic", timeout=600)
        with open(os.path.join(args.out, "journal-isp-channel.log"), "w") as f:
            f.write(journal + "\n")
        with open(os.path.join(args.out, "journal-boot.log"), "w") as f:
            f.write(guest.run("journalctl -b --no-pager -o short-monotonic", timeout=900) + "\n")
        info.append(guest.run("ls -la /var/lib/isp-channel", check=False))
        info.append(guest.run("df -h /", check=False))
        with open(os.path.join(args.out, "system-info.txt"), "w") as f:
            f.write("\n\n".join(info) + "\n")
        guest.run("sync")
    finally:
        guest.poweroff()

    # Pull the results out of the root filesystem image.
    media = os.path.join(work, "media")
    os.makedirs(media)
    subprocess.run(["debugfs", "-R", f"rdump /var/lib/isp-channel {media}", rootfs],
                   check=True, capture_output=True)
    media = os.path.join(media, "isp-channel")
    recordings = sorted(glob.glob(os.path.join(media, "isp-*.mp4")))
    snapshots = sorted(glob.glob(os.path.join(media, "snapshot-*.png")))
    for i, path in enumerate(snapshots):
        shutil.copy(path, os.path.join(args.out, f"snapshot-{i + 1}.png"))
    if recordings:
        shutil.copy(recordings[0], os.path.join(args.out, "recording-first-segment.mp4"))

    stats, summary = parse_stats(journal)
    check(summary is not None, "service printed its exit summary (clean shutdown)")
    check(len(stats) >= 3, "periodic statistics were logged")
    if not summary or len(stats) < 3:
        sys.exit(1)

    encoded = None
    if shutil.which("ffprobe"):
        encoded = 0
        for path in recordings:
            out = subprocess.run(["ffprobe", "-v", "error", "-count_frames", "-select_streams", "v:0",
                                  "-show_entries", "stream=nb_read_frames", "-of", "csv=p=0", path],
                                 capture_output=True, text=True).stdout.strip()
            encoded += int(out) if out.isdigit() else 0

    psnr_match = re.search(r"PSNR ([0-9.]+) dB", journal)
    psnr = psnr_match.group(1) if psnr_match else "n/a"
    rss = column(stats, "rss_mib")

    check(float(summary["seconds"]) >= args.soak, f"streamed for at least {args.soak} s")
    check(summary["dropped"] == "0", "no dropped frames")
    check(summary["failed"] == "0", "no failed or cancelled frames")
    check(max(rss[1:]) - min(rss[1:]) < 16.0, "no memory growth (RSS within 16 MiB after warm-up)")
    check(len(snapshots) == 2, "two PNG snapshots (control socket and SIGUSR1)")
    check(psnr != "n/a" and float(psnr) >= 25.0, f"ISP round-trip PSNR {psnr} dB >= 25 dB")
    check(len(recordings) >= 1, "MP4 recording present")
    check(len(recordings) <= RING_FILES, f"recording ring holds at most {RING_FILES} segments")
    if encoded is not None and len(recordings) < RING_FILES:
        # Only comparable while the ring has not started deleting old segments.
        check(encoded == int(summary["frames"]),
              f"every captured frame was encoded ({encoded} of {summary['frames']})")
    elif encoded is not None:
        check(0 < encoded <= int(summary["frames"]),
              f"ring is full: the newest {len(recordings)} segments hold {encoded} of "
              f"{summary['frames']} frames")
    check("control Brightness" in journal and "tungsten" in journal, "run-time control changes applied")

    write_measurements(os.path.join(args.out, "measurements.md"), args, stats, summary,
                       samples, bench, psnr, encoded)
    shutil.rmtree(work, ignore_errors=True)
    print(f"evidence written to {args.out}")
    sys.exit(1 if failures else 0)


if __name__ == "__main__":
    main()
